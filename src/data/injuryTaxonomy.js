export const getInjuryById = (id) => INJURY_TAXONOMY.find(item => item.id === id);
export const searchInjuries = (query) => {
  if (!query) return INJURY_TAXONOMY;
  const q = query.toLowerCase();
  return INJURY_TAXONOMY.filter(i => 
    i.name.toLowerCase().includes(q) ||
    i.body_region.toLowerCase().includes(q) ||
    i.tissue_type.toLowerCase().includes(q) ||
    i.sport_examples.some(s => s.toLowerCase().includes(q)) ||
    i.icd_codes['ICD-10']?.toLowerCase().includes(q)
  );
};
